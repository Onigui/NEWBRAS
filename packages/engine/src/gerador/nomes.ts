const GRUPO_PADRAO = "en";

export function gruposDeNomes(): string[] {
  return Object.keys(GRUPOS);
}

function diminutivo(nome: string): string {
  const base = nome.normalize("NFD").replace(/[̀-ͯ]/g, "");
  if (/[aeiou]$/i.test(base)) return `${base.slice(0, -1)}inho`;
  return `${base}inho`;
}

/** Sorteia nome de camisa e nome completo para um jogador do grupo indicado. */
export function gerarNome(rng: Rng, grupo: string): { nome: string; nomeCompleto: string } {
  const g = GRUPOS[grupo] ?? GRUPOS[GRUPO_PADRAO]!;
  const primeiro = rng.pick(g.nomes);
  const sobrenome = rng.pick(g.sobrenomes);
  const nomeCompleto =
    g.estilo === "nome-sobrenome" ? `${sobrenome} ${primeiro}` : `${primeiro} ${sobrenome}`;

  let nome: string;
  if (g.estilo === "brasileiro") {
    // No Brasil a camisa costuma levar o primeiro nome, um apelido ou o sobrenome.
    const sorteio = rng.next();
    nome =
      sorteio < 0.45
        ? primeiro
        : sorteio < 0.6
          ? diminutivo(primeiro)
          : sorteio < 0.8
            ? sobrenome
            : `${primeiro} ${sobrenome}`;
  } else if (g.estilo === "nome-sobrenome") {
    nome = `${sobrenome} ${primeiro}`;
  } else {
    nome = sobrenome;
  }
  return { nome, nomeCompleto };
}
