/** Rivais entre clubes dos EUA e do Canadá ficam com o prefixo do país certo. */
function corrigirRivais(clubes: ClubeEntrada[]): ClubeEntrada[] {
  const porSufixo = new Map(clubes.map((c) => [c.id.slice(4), c.id]));
  return clubes.map((c) => ({
    ...c,
    rivais: (c.rivais ?? []).map((r) => porSufixo.get(r.slice(4)) ?? r),
  }));
}

