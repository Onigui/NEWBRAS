import type { CompeticaoEntrada } from "@newbras/data";
import { clubesDe, type ClubeLinha } from "../tipos";
import { liga, playoffIdaEVolta, rodadaUnica } from "./liga";

/**
 * Países de nível 3 das Américas: só a primeira divisão, sem acesso nem rebaixamento (a segunda
 * divisão não está no banco). Clubes, cidades, estádios e capacidades conferidos nas páginas da
 * temporada 2026 (2026/27 na América Central) da Wikipédia; quando a página da temporada não
 * existia, a lista vem da página da liga (temporada anterior) e o detalhe fica em
 * `docs/fontes-banco.md`. Cores incertas ficam "a conferir".
 */

type Fase = CompeticaoEntrada["fases"][number];

interface PaisNivel3 {
  pais: string;
  id: string;
  nome: string;
  nomeCurto: string;
  linhas: readonly ClubeLinha[];
  calendario: { inicio: string; fim: string };
  playoff?: { de: number; ate: number; fases: readonly Fase[] };
  estrangeiros: readonly string[];
  fracaoEstrangeiros: number;
  fimDeContrato: string;
}

function montar(p: PaisNivel3) {
  const prefixo = p.pais.toLowerCase();
  return {
    clubes: clubesDe(p.pais, p.linhas),
    competicoes: [
      liga({
        pais: p.pais,
        id: p.id,
        nome: p.nome,
        nomeCurto: p.nomeCurto,
        divisao: 1,
        clubes: p.linhas.map((l) => `${prefixo}-${l[0]}`),
        calendario: p.calendario,
        desempate: ["pontos", "saldo", "gols-pro", "confronto-direto", "sorteio"],
        ...(p.playoff ? { playoff: p.playoff } : {}),
        movimentos: [],
      }),
    ],
    estrangeiros: p.estrangeiros,
    fracaoEstrangeiros: p.fracaoEstrangeiros,
    fimDeContrato: p.fimDeContrato,
  };
}

